export const JALALI_WEEKDAYS = ["شنبه", "یکشنبه", "دوشنبه", "سه‌شنبه", "چهارشنبه", "پنجشنبه", "جمعه"];

/** Fridays and official Nowruz holidays marked as peak by default. */
export function isWeekendIso(iso: string): boolean {
  const [gy, gm, gd] = iso.split("-").map(Number);
  return new Date(Date.UTC(gy, gm - 1, gd)).getUTCDay() === 5;
}

export function jalaliLabelFromIso(iso: string): string {
  const { jy, jm, jd } = jalaliFromIso(iso);
  return `${jd} ${JALALI_MONTH_NAMES[jm - 1]} ${jy}`;
}
